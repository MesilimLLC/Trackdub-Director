// Generated Vite output is not tracked in git.
// Run `npm run build` in web/ to regenerate the workbench bundle.
function showBuildNotice(doc) {
  const root = doc.getElementById("root");
  if (root) {
    root.textContent = "The workbench UI is not built. Run `npm run build` in web/.";
  }
}
showBuildNotice(document);
